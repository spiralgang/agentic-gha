"""FSM Compiler: Spec (.md layouts) -> standalone Python module.

The generated module (``fsm_compiled.py``) is a complete, runnable finite
state machine: it bakes the states, transitions, parameters, per-state
instructions and vault entries from the markdown specs into Python literals,
plus a ``CompiledFSM`` engine that evaluates guards and applies actions.

Guards are read-only boolean expressions evaluated over the FSM context
(no builtins available). Actions are a tiny, safe assignment language
(``var = expr``, ``var += n``, ``var -= n``) so the compiler never exec's
arbitrary generated code.
"""

from __future__ import annotations

import json
import os
from typing import List, Tuple

from spec_parser import Spec

_ENGINE_TEMPLATE = '''\
# AUTO-GENERATED by fsm.compiler -- do not edit by hand.
# Compiled from repository .md layouts (PLANS / COPILOT_INSTRUCTIONS /
# AGENT_INSTRUCTIONS / VAULT). Re-run the compiler to regenerate.

import re as _re

NAME = {name!r}
INITIAL = {initial!r}
STATES = {states!r}
TRANSITIONS = {transitions!r}
PARAMS = {params!r}
INSTRUCTIONS = {instructions!r}
VAULT = {vault!r}

_DEFAULT_CTX = {{"attempt": 0, "cycle": 0, "verdict": "", "last_action": ""}}


class CompiledFSM:
    """A finite state machine compiled from markdown specs."""

    def __init__(self, on_enter=None, decide=None, on_transition=None, max_steps=1000):
        self.on_enter = on_enter
        self.decide = decide
        self.on_transition = on_transition
        self.max_steps = max_steps
        self.state = None
        self.ctx = {{}}
        self.history = []
        self.steps = 0

    # -- lifecycle ---------------------------------------------------------
    def start(self):
        self.ctx = dict(PARAMS)
        for k, v in _DEFAULT_CTX.items():
            self.ctx.setdefault(k, v)
        self.state = INITIAL
        if self.on_enter:
            self.on_enter(self.state, self.ctx, INSTRUCTIONS.get(self.state, ""))

    # -- guard / action evaluation ----------------------------------------
    @staticmethod
    def _eval_guard(expr, ctx):
        try:
            return bool(eval(expr, {{"__builtins__": {{}}}}, dict(ctx)))
        except Exception:
            return False

    def _apply_action(self, action):
        for part in action.split(";"):
            part = part.strip()
            if not part:
                continue
            m = _re.match(r"^([A-Za-z_]\\w*)\\s*([+\\-]=|=)\\s*(.+)$", part)
            if not m:
                continue
            var, op, rhs = m.groups()
            try:
                val = eval(rhs, {{"__builtins__": {{}}}}, dict(self.ctx))
            except Exception:
                continue
            if op == "=":
                self.ctx[var] = val
            elif op == "+=":
                self.ctx[var] = self.ctx.get(var, 0) + val
            elif op == "-=":
                self.ctx[var] = self.ctx.get(var, 0) - val
        self.ctx["last_action"] = action

    # -- stepping ----------------------------------------------------------
    def step(self):
        if self.state is None:
            self.start()
        if self.decide:
            upd = self.decide(self.state, dict(self.ctx))
            if isinstance(upd, dict):
                self.ctx.update(upd)
        for (frm, to, guard, action) in TRANSITIONS:
            if frm != self.state:
                continue
            if self._eval_guard(guard, self.ctx):
                if action:
                    self._apply_action(action)
                prev = self.state
                self.state = to
                self.steps += 1
                self.history.append((prev, to, guard, action))
                if self.on_transition:
                    self.on_transition(prev, to, guard, action, self.ctx)
                if self.on_enter:
                    self.on_enter(to, self.ctx, INSTRUCTIONS.get(to, ""))
                return (prev, to)
        return None  # terminal state: no enabled transition

    def run(self):
        if self.state is None:
            self.start()
        while self.steps < self.max_steps:
            if self.step() is None:
                break
        return self.history
'''


def compile_source(spec: Spec) -> str:
    """Return the generated Python source for the compiled FSM."""
    states_repr = {k: v for k, v in spec.states.items()}
    transitions_repr: List[Tuple[str, str, str, str]] = [
        (f, t, g, a) for (f, t, g, a) in spec.transitions
    ]
    return _ENGINE_TEMPLATE.format(
        name=spec.name,
        initial=spec.initial,
        states=states_repr,
        transitions=transitions_repr,
        params=spec.params,
        instructions=spec.instructions,
        vault=spec.vault,
    )


def compile_to_file(spec: Spec, out_path: str) -> str:
    source = compile_source(spec)
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(source)
    return out_path
